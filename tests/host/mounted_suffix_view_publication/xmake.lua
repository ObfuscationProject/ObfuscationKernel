set_project("Concrete mounted suffix View publication source prototype")
set_languages("c++23")
add_rules("mode.release")
option("sanitizers")
    set_default(false)
    set_showmenu(true)
option_end()
add_includedirs("../../../include", "..")
add_cxxflags("-fno-exceptions", "-O2", "-Wall", "-Wextra", "-Werror", {force = true})
if has_config("sanitizers") then
    add_cxxflags("-fsanitize=address,undefined", "-fno-omit-frame-pointer", {force = true})
    add_ldflags("-fsanitize=address,undefined", {force = true})
end
target("mounted-suffix-view-publication-model")
    set_kind("binary")
    add_files("model.cpp", "../../../src/fs/ext4_recovery.cpp", "../ext4_realtime_model.cpp")
    add_cxxflags("-fno-access-control", {force = true})
target_end()
target("mounted-suffix-view-publication-freestanding")
    set_kind("static")
    add_files("compile.cpp")
    add_cxxflags("-ffreestanding", "-fno-stack-protector", "-fno-use-cxa-atexit", "-fno-threadsafe-statics", "-fstack-usage", {force = true})
target_end()
