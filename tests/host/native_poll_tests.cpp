#include <cstdlib>
#include <cstring>

using namespace ok;
namespace native = ok::user::native;
namespace hw = ok::arch::execution;
#define CHECK(x) do { if (!(x)) { std::fprintf(stderr, "%d: %s\n", __LINE__, #x); std::abort(); } } while (false)
namespace mock {
std::array<std::byte, 4096> memory{};
bool writable = true;
}
namespace ok::arch {
Status initialize_clock() { return Status::success(); }
Result<u64> monotonic_nanoseconds() { return u64{3000000042}; }
u64 clock_resolution_ns() { return 1; }
}
namespace ok::arch::execution {
bool supported() noexcept { return false; }
OwnershipReport ownership_report() noexcept { return {}; }
Status initialize() { return Status::unsupported(); }
Result<AddressSpace> create_space(MappingView) { return Status::unsupported(); }
Status destroy_space(AddressSpace &space) { space = {}; return Status::success(); }
Result<Trap> enter_owned(AddressSpace &space, UserFrame &frame, const KernelEntryStackView &view)
{
    if (!view.valid()) return Status::invalid_argument("hosted entry requires a live lease");
    auto result = enter(space, frame);
    if (result) result.value().kernel_stack_pointer = view.lower(); // Synthetic hosted capture only.
    return result;
}
Result<Trap> enter(AddressSpace &, UserFrame &) { return Status::unsupported(); }
UserFrame initial_frame(uptr pc, uptr sp) { UserFrame f{}; f.pc=pc; f.sp=sp; return f; }
Syscall syscall(const UserFrame &) { return {}; }
void set_return_value(UserFrame &frame, i64 value) { frame.registers[0] = static_cast<uptr>(value); }
bool user_range(const AddressSpace &, uptr address, usize size, bool write) {
    return size == 0 || ((mock::writable || !write) && address >= user_begin &&
        address - user_begin <= mock::memory.size() && size <= mock::memory.size() - (address-user_begin));
}
Status copy_from_user(const AddressSpace &space, void *out, uptr address, usize size) {
    if (!user_range(space,address,size,false)) return Status::fault();
    if(size) std::memcpy(out, mock::memory.data()+address-user_begin,size);
    return Status::success();
}
Status copy_to_user(const AddressSpace &space, uptr address, const void *in, usize size) {
    if (!user_range(space,address,size,true)) return Status::fault();
    if(size) std::memcpy(mock::memory.data()+address-user_begin,in,size);
    return Status::success();
}
}

int main() {
    static Kernel kernel;
    CHECK(kernel.boot({}));
    auto created = kernel.scheduler().create_user_process("poll-fixture", kernel.arch().make_user_context({hw::user_begin, hw::user_end-4096}));
    CHECK(created);
    const auto pid = created.value();
    CHECK(kernel.posix().activate(pid));
    auto *process = kernel.scheduler().find(pid);
    process->threads()[0].native_active = true;
    // Exercise actual personality adapters against the shared native boundary.
    // Register/byte layouts are explicit golden inputs, not generated by the adapter.
    using Profile = abi::linux_user::Profile;
    auto shared = [&](hw::Syscall call, bool &done) { return native::dispatch(kernel,pid,call,done); };
    hw::UserFrame linux{};
    bool linux_done = true;
    linux.registers[14] = 3; linux.registers[9] = ~uptr{0}; // x86_64 close(-1)
    CHECK(user::linux_bootstrap::dispatch<Profile::x86_64>(kernel,pid,linux,linux_done,shared) == -9);
    linux.registers[14] = 0; // read(-1, unmapped, 1) validates the descriptor first.
    linux.registers[10] = 0; linux.registers[11] = 1;
    CHECK(user::linux_bootstrap::dispatch<Profile::x86_64>(kernel,pid,linux,linux_done,shared) == -9);
    linux.registers[9] = 1; // stdout is not readable.
    CHECK(user::linux_bootstrap::dispatch<Profile::x86_64>(kernel,pid,linux,linux_done,shared) == -9);
    linux.registers[14] = 218; linux.registers[9] = ~uptr{0};
    CHECK(user::linux_bootstrap::dispatch<Profile::x86_64>(kernel,pid,linux,linux_done,shared) ==
          static_cast<i64>(pid));
    CHECK(process->threads()[0].tls.clear_tid_address == ~uptr{0});
    linux.registers[14] = 158; linux.registers[9] = 0x1002; linux.registers[10] = hw::user_begin+512;
    CHECK(user::linux_bootstrap::dispatch<Profile::x86_64>(kernel,pid,linux,linux_done,shared) == 0);
    CHECK(linux.fs_base == hw::user_begin+512);
    linux.registers[14] = 205;
    CHECK(user::linux_bootstrap::dispatch<Profile::x86_64>(kernel,pid,linux,linux_done,shared) == -38);
    linux = {};
    linux.registers[2] = 4403; linux.registers[4] = 1; linux.registers[5] = hw::user_begin+128;
    CHECK(user::linux_bootstrap::dispatch<Profile::mips>(kernel,pid,linux,linux_done,shared) == 0);
    const std::array<u8,16> time64{0,0,0,0,0,0,0,3,0,0,0,0,0,0,0,42};
    CHECK(std::memcmp(mock::memory.data()+128,time64.data(),time64.size()) == 0);
    CHECK(user::linux_bootstrap::complete<Profile::mips>(linux,-38));
    CHECK(linux.registers[2] == 89 && linux.registers[7] == 1);
    CHECK(!user::linux_bootstrap::complete<Profile::mips>(linux,INT64_MIN));
    CHECK(linux.registers[2] == 89 && linux.registers[7] == 1);
    linux = {};
    linux.registers[7] = 243; linux.registers[4] = hw::user_begin+256;
    std::array<u32,4> user_desc{~u32{0},static_cast<u32>(hw::user_begin+512),0xfffff,0x51};
    std::memcpy(mock::memory.data()+256,user_desc.data(),sizeof(user_desc));
    CHECK(user::linux_bootstrap::dispatch<Profile::i386>(kernel,pid,linux,linux_done,shared) == 0);
    std::memcpy(user_desc.data(),mock::memory.data()+256,sizeof(user_desc));
    CHECK(user_desc[0] == 7 && linux.gs_base == hw::user_begin+512 && linux.registers[8] == 0x3b);
    linux.registers[7] = 90;
    CHECK(user::linux_bootstrap::dispatch<Profile::i386>(kernel,pid,linux,linux_done,shared) == -38);
    auto pipes = kernel.posix().pipe(posix::o_NONBLOCK);
    CHECK(pipes);
    const auto readfd = pipes.value()[0], writefd = pipes.value()[1];
    const auto reader = process->fd_table().entry(readfd)->description;
    const auto writer = process->fd_table().entry(writefd)->description;
    std::array<ok_pollfd, 2> input{{{readfd, OK_POLLIN, 99}, {readfd, OK_POLLIN, 88}}};
    std::memcpy(mock::memory.data(), input.data(), sizeof(input));
    bool complete = true;
    CHECK(native::dispatch(kernel,pid,{OK_SYS_POLL,{hw::user_begin,2,~uptr{0},0,0,0}},complete) == 0 && !complete);
    CHECK(process->state() == sched::ProcessState::blocked);
    CHECK(kernel.scheduler().open_description(reader)->references == 3);
    const auto object = native::poll_waits[0].object;
    auto resolved = native::poll_objects.resolve(object);
    CHECK(resolved);
    auto &wait = *resolved.value();
    CHECK(wait.pid == pid && wait.count == 2);
    // Request mutation and descriptor reuse cannot redirect the retained wait.
    input[0] = {writefd, OK_POLLOUT, 77};
    std::memcpy(mock::memory.data(), input.data(), sizeof(input));
    CHECK(kernel.scheduler().close_descriptor(process->resources(), readfd));
    CHECK(kernel.scheduler().install_descriptor(process->resources(), readfd, writer));
    CHECK(kernel.scheduler().open_description(reader)->references == 2);
    CHECK(native::poll_ready(kernel,wait).value() == 0);
    const std::byte byte{42};
    CHECK(kernel.scheduler().write_pipe(kernel.scheduler().open_description(writer)->pipe,{&byte,1},true));
    CHECK(native::poll_ready(kernel,wait).value() == 2);
    CHECK(native::poll_output(process->resources().native_space,wait));
    std::memcpy(input.data(), mock::memory.data(), sizeof(input));
    CHECK(input[0].fd == writefd && input[0].events == OK_POLLOUT && input[0].revents == OK_POLLIN);
    CHECK(input[1].revents == OK_POLLIN);
    mock::writable=false;
    CHECK(!native::poll_output(process->resources().native_space,wait));
    mock::writable=true;
    // Teardown releases both reader pins; the reused fd remains a writer.
    native::release_process(kernel,pid);
    CHECK(!native::poll_objects.resolve(object) && !process->threads()[0].native_active);
    CHECK(native::page_pool.object_count() == 0);
    CHECK(kernel.scheduler().open_description(reader) == nullptr);
    auto ready = kernel.posix().ready_description(writer,posix::ReadyEvents::none);
    CHECK(ready && ready.value().events == posix::ReadyEvents::error);
    native::release_process(kernel,pid);
    CHECK(kernel.scheduler().open_description(writer)->references == 2);
    CHECK(kernel.scheduler().terminate_process(pid,9));
    CHECK(kernel.scheduler().open_description(writer) == nullptr);
    CHECK(native::poll_waits[0].pid == 0);
    std::puts("PASS hosted native poll: frozen request, duplicate pins, fd reuse, copy fault, teardown and peer error");
    std::puts("PASS hosted Linux bootstrap adapter: shared close, x86 TLS, i386 user_desc, MIPS time64/errno");
}
