#!/usr/bin/env python3
"""Independent struct/network-order golden packets; imports no kernel codec."""
from pathlib import Path
import argparse
import struct


def checksum(data):
    padded = data + (b'\0' if len(data) & 1 else b'')
    value = sum(struct.unpack('!' + 'H' * (len(padded) // 2), padded))
    while value > 65535:
        value = (value & 65535) + (value >> 16)
    return (~value) & 65535


def packet(source, destination, identity, ttl, fields, options, payload):
    padding = b'\0' * ((-len(options)) % 4)
    header = 20 + len(options) + len(padding)
    sp, dp, sequence, acknowledgment, flags, window, urgent = fields
    segment = struct.pack('!HHIIBBHHH', sp, dp, sequence, acknowledgment,
        (header // 4) << 4, flags, window, 0, urgent) + options + padding + payload
    pseudo = bytes(source) + bytes(destination) + struct.pack('!BBH', 0, 6, len(segment))
    value = checksum(pseudo + segment)
    segment = segment[:16] + struct.pack('!H', value) + segment[18:]
    ip = struct.pack('!BBHHHBBH4s4s', 0x45, 0, 20 + len(segment), identity,
        0x4000, ttl, 6, 0, bytes(source), bytes(destination))
    ip = ip[:10] + struct.pack('!H', checksum(ip)) + ip[12:]
    assert checksum(ip) == checksum(pseudo + segment) == 0
    return ip + segment


def render():
    source, destination = (192, 0, 2, 1), (198, 51, 100, 2)
    vectors = [
        ('syn', 0x1234, 64, (49152, 80, 0x01020304, 0, 2, 65535, 0), b'', b''),
        ('odd', 0xabcd, 127, (12345, 443, 0xffffffff, 0x80000001, 0x18, 32768, 0x4001), b'', b'hello'),
        ('options', 0x0001, 1, (80, 49152, 0x80000000, 0xffffffff, 0xc2, 4096, 0x1234),
            bytes.fromhex('01020405b4fd03aa'), b''),
        ('max-options', 0xffff, 255, (0, 65535, 0, 0xffffffff, 0xff, 0, 65535), b'\1' * 40, b'abc'),
        ('pad-options', 0x3333, 32, (777, 888, 0x12345678, 0x90abcdef, 0x10, 65535, 7),
            bytes.fromhex('fd03aa'), b'\0\xff'),
    ]
    fields = (111, 222, 0x01010101, 0x02020202, 0x30, 321, 0)
    initial = packet(source, destination, 9, 64, fields, b'', b'Z')
    urgent = struct.unpack_from('!H', initial, 36)[0]
    zero_fields = fields[:-1] + (urgent,)
    assert packet(source, destination, 9, 64, zero_fields, b'', b'Z')[36:38] == b'\0\0'
    vectors.append(('zero-checksum', 9, 64, zero_fields, b'', b'Z'))
    lines = ['#pragma once', '', '// Generated by independent tcp_wire_vectors.py.',
        'namespace tcp_vectors', '{', 'struct Golden', '{',
        '    const char *name;', '    ok::net::wire::Ipv4 source, destination;',
        '    ok::u16 identification;', '    ok::u8 ttl;', '    ok::net::wire::TcpFields fields;',
        '    ok::net::wire::Bytes options, payload, packet;', '};']
    for index, (name, identity, ttl, fields, options, payload) in enumerate(vectors):
        encoded = packet(source, destination, identity, ttl, fields, options, payload)
        for suffix, data in (('options', options), ('payload', payload), ('packet', encoded)):
            text = ', '.join('std::byte{0x%02x}' % value for value in data)
            lines.append('inline constexpr std::array<std::byte, %d> v%d_%s{%s};' %
                (len(data), index, suffix, text))
        fields_text = ', '.join(str(value) + 'u' for value in fields)
        lines.append('inline constexpr Golden v%d{"%s", {192,0,2,1}, {198,51,100,2}, %du, %du, {%s}, v%d_options, v%d_payload, v%d_packet};' %
            (index, name, identity, ttl, fields_text, index, index, index))
    lines.append('inline constexpr std::array<Golden, %d> all{%s};' %
        (len(vectors), ', '.join('v%d' % i for i in range(len(vectors)))))
    lines.extend(('}', ''))
    return '\n'.join(lines)


if __name__ == '__main__':
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--output', type=Path, required=True)
    cli.add_argument('--check', action='store_true')
    args = cli.parse_args()
    text = render()
    if args.check:
        assert args.output.read_text() == text, 'Independent checked-in golden vectors differ'
    else:
        with args.output.open('x') as stream:
            stream.write(text)
    print('TCP_INDEPENDENT_GOLDENS_PASS vectors=6')
