set_project("prepared-tcp-accept-leaf")
set_version("0.1.0")
set_languages("cxx23")
add_rules("mode.debug", "mode.release")
local source = os.getenv("PREPARED_TCP_ACCEPT_SOURCE")
local cxx = os.getenv("PREPARED_TCP_ACCEPT_CXX")
local cc = os.getenv("PREPARED_TCP_ACCEPT_CC")
local kind = os.getenv("PREPARED_TCP_ACCEPT_KIND")
local dependency = os.getenv("PREPARED_TCP_ACCEPT_DEPFILE")
toolchain("prepared-tcp-accept-selected")
    set_kind("standalone")
    on_check(function ()
        assert(source and os.isdir(source), "explicit private source required")
        assert(kind == "hosted" or kind == "sanitized", "hosted model qualification required")
        assert(os.isfile(cxx) and os.isfile(cc), "exact selected compiler required")
        assert(dependency and #dependency > 0, "explicit original compile dependency file required")
        return true
    end)
    on_load(function (toolchain)
        toolchain:set("toolset", "cxx", cxx)
        toolchain:set("toolset", "cc", cc)
        toolchain:set("toolset", "ld", cxx)
    end)
toolchain_end()
target("prepared-tcp-accept")
    set_kind("binary")
    set_toolchains("prepared-tcp-accept-selected")
    add_includedirs(path.join(source, "include"))
    add_files(path.join(source, "tests/host/prepared_tcp_accept_tests.cpp"))
    add_cxxflags("-std=c++23", "-Wall", "-Wextra", "-Werror", "-fno-exceptions", {force = true})
    add_cxxflags("-MD", "-MF", dependency, {force = true})
    if kind == "sanitized" then
        add_cxxflags("-fsanitize=address,undefined", "-fno-omit-frame-pointer", {force = true})
        add_ldflags("-fsanitize=address,undefined", {force = true})
    end
target_end()
