set_project("Architecture-independent Session accounting model")
set_languages("c++23")
add_rules("mode.debug", "mode.release")
option("sanitizers")
    set_default(false)
    set_showmenu(true)
option_end()
if has_config("sanitizers") then
    add_cxxflags("-fsanitize=address,undefined", "-fno-omit-frame-pointer", {force = true})
    add_ldflags("-fsanitize=address,undefined", {force = true})
end
target("wide-session-arithmetic-model")
    set_kind("binary")
    add_files("model.cpp")
    add_includedirs("../../../include")
    add_cxxflags("-fno-exceptions", "-O2", "-Wall", "-Wextra", "-Werror", {force = true})
target_end()
target("wide-session-block-model")
    set_kind("binary")
    add_files("../block_sessions_tests.cpp")
    add_includedirs("../../../include")
    add_cxxflags("-pthread", "-fno-exceptions", "-O2", "-Wall", "-Wextra", "-Werror", {force = true})
    add_ldflags("-pthread", {force = true})
target_end()
target("wide-session-budget-model")
    set_kind("binary")
    add_files("../ext4_mounted_typed_budget_tests.cpp")
    add_includedirs("../../../include")
    add_cxxflags("-fno-exceptions", "-fno-access-control", "-O2", "-Wall", "-Wextra", "-Werror", {force = true})
target_end()
target("wide-session-freestanding")
    set_kind("static")
    add_files("../block_sessions_compile.cpp", "../ext4_mounted_typed_budget_compile.cpp")
    add_includedirs("../../../include")
    add_cxxflags("-ffreestanding", "-fno-exceptions", "-fno-stack-protector", "-fno-use-cxa-atexit", "-fno-threadsafe-statics", "-O2", "-Wall", "-Wextra", "-Werror", "-fstack-usage", {force = true})
target_end()
