#!/usr/bin/env python3
"""Generate the narrow AF_UNIX syscall-number extension from pinned musl headers."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

PORTS = ("i386", "x86_64", "aarch64", "arm", "riscv64", "riscv32",
         "loongarch64", "mips", "mips64", "powerpc")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--musl-source", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    manifest = json.loads((root / "docs/abi/linux-profiles.json").read_text())
    rows = []
    for port in PORTS:
        relative = f"arch/{port}/bits/syscall.h.in"
        source = args.musl_source / relative
        data = source.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if digest != manifest["source_file_sha256"]["musl/" + relative]:
            raise ValueError(f"pinned musl source hash mismatch: {relative}")
        definitions = dict(re.findall(r"^#define\s+(__NR_\w+)\s+(\d+)\s*$", data.decode(), re.M))
        direct = int(definitions["__NR_socketpair"])
        legacy = int(definitions.get("__NR_socketcall", "0"))
        rows.append((direct, legacy, digest))
    lines = [
        "#pragma once", "", "// Generated by scripts/generate_linux_socketpair.py from pinned musl 1.2.5 headers.",
        '#include "ok/abi/linux_pipe.hpp"', "", "namespace ok::abi::linux_user", "{",
        "struct SocketPairNumbers { u32 direct; u32 legacy_socketcall; };",
        "inline constexpr std::array<SocketPairNumbers, static_cast<usize>(Profile::count)> socketpair_numbers{{",
    ]
    for direct, legacy, digest in rows:
        lines.append(f"    {{{direct}u, {legacy}u}}, // musl source SHA-256 {digest}")
    lines += [
        "}};", "template <Profile Selected> requires SupportedProfile<Selected>",
        "class SocketPairCodec final", "{", "  public:",
        "    static constexpr SocketPairNumbers numbers = socketpair_numbers[static_cast<usize>(Selected)];",
        "    static constexpr u32 stream = Selected == Profile::mips || Selected == Profile::mips64 ? 2u : 1u;",
        "    static Result<u32> decode_type(u32 type)", "    {",
        "        using Flags = OpenCodec<Selected>;",
        "        if ((type & 0xfu) != stream || (type & ~(0xfu | Flags::nonblock | Flags::cloexec)))",
        "            return Status::invalid_argument(\"unsupported Linux AF_UNIX socket type\");",
        "        return ((type & Flags::nonblock) ? posix::o_NONBLOCK : 0u) |",
        "               ((type & Flags::cloexec) ? posix::o_CLOEXEC : 0u);",
        "    }", "};", "} // namespace ok::abi::linux_user", "",
    ]
    output = "\n".join(lines)
    target = root / "include/ok/abi/linux_socketpair.hpp"
    if args.check:
        if target.read_text() != output:
            raise ValueError("generated AF_UNIX ABI table is stale")
    else:
        target.write_text(output)
    print("verified ten pinned musl socketpair profiles")


if __name__ == "__main__":
    main()
