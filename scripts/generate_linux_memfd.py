#!/usr/bin/env python3
"""Generate the bounded memfd ABI extension from the exact pinned musl archive."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import tarfile

PORTS = ("i386", "x86_64", "aarch64", "arm", "riscv64", "riscv32",
         "loongarch64", "mips", "mips64", "powerpc")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--musl-archive", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    manifest = json.loads((root / "docs/abi/linux-profiles.json").read_text())
    digest = hashlib.sha256(args.musl_archive.read_bytes()).hexdigest()
    if digest != manifest["musl_archive_sha256"]:
        raise ValueError("pinned musl archive hash mismatch")
    files = {}
    with tarfile.open(args.musl_archive, "r:gz") as archive:
        def read(relative):
            name = "musl-" + manifest["musl_version"] + "/" + relative
            member = archive.getmember(name)
            if not member.isfile():
                raise ValueError("exact musl member is not a regular file: " + name)
            data = archive.extractfile(member).read()
            files[relative] = hashlib.sha256(data).hexdigest()
            expected = manifest["source_file_sha256"].get("musl/" + relative)
            if expected and expected != files[relative]:
                raise ValueError("pinned musl source hash mismatch: " + relative)
            return dict(re.findall(r"^#define\s+([A-Za-z_][A-Za-z_0-9]*)\s+(0x[0-9a-fA-F]+|[0-9]+)[uUlL]*\s*$",
                                   data.decode(), re.M))
        mmap = read("include/sys/mman.h")
        fcntl = read("include/fcntl.h")
        constants = {name: int((mmap if name.startswith("MFD_") else fcntl)[name], 0)
                     for name in ("MFD_CLOEXEC", "MFD_ALLOW_SEALING", "F_ADD_SEALS", "F_GET_SEALS",
                                  "F_SEAL_SEAL", "F_SEAL_SHRINK", "F_SEAL_GROW", "F_SEAL_WRITE", "F_SEAL_FUTURE_WRITE")}
        numbers = [int(read(f"arch/{port}/bits/syscall.h.in")["__NR_memfd_create"], 0) for port in PORTS]
    lines = ["#pragma once", "", "// Generated by scripts/generate_linux_memfd.py from the exact musl 1.2.5 archive.",
             '#include "ok/abi/linux_open.hpp"', "", "namespace ok::abi::linux_user", "{"]
    lines += ["inline constexpr std::array<u32, static_cast<usize>(Profile::count)> memfd_numbers{{",
              "    " + ", ".join(str(number) + "u" for number in numbers), "}};"]
    lines += ["template <Profile Selected> requires SupportedProfile<Selected>", "class MemfdCodec final", "{", "  public:",
              "    static constexpr u32 number = memfd_numbers[static_cast<usize>(Selected)];"]
    for name, value in constants.items():
        lines.append("    static constexpr u32 " + name.lower() + " = " + str(value) + "u;")
    lines += ["    static Result<u32> decode_flags(u32 flags)", "    {",
              "        if (flags & ~(mfd_cloexec | mfd_allow_sealing))",
              '            return Status::invalid_argument("unsupported Linux memfd creation flag");',
              "        if (!(flags & mfd_allow_sealing))",
              '            return Status::unsupported("bounded Linux memfd requires sealing permission");',
              "        return ((flags & mfd_cloexec) ? posix::mfd_CLOEXEC : 0u) | posix::mfd_ALLOW_SEALING;", "    }",
              "    static Result<u32> decode_seals(u32 seals)", "    {",
              "        if (seals & ~(f_seal_seal | f_seal_shrink | f_seal_grow | f_seal_write))",
              '            return Status::unsupported("Linux memfd seal is not admitted");',
              "        return seals;", "    }", "};", "} // namespace ok::abi::linux_user", ""]
    outputs = {root / "include/ok/abi/linux_memfd.hpp": "\n".join(lines),
               root / "docs/abi/linux-memfd.json": json.dumps(dict(schema=1,
                   scope="bounded-sealed-size-write-memfd-codec", musl_version=manifest["musl_version"],
                   musl_archive_sha256=digest, source_file_sha256=files, ports=list(PORTS),
                   syscall_numbers=numbers, constants=constants), indent=2, sort_keys=True) + "\n"}
    for target, content in outputs.items():
        if args.check:
            if target.read_text() != content:
                raise ValueError("generated memfd ABI data is stale: " + str(target))
        else:
            target.write_text(content)
    print("verified ten pinned musl memfd profiles")


if __name__ == "__main__":
    main()
